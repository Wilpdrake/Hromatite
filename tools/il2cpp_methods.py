#!/usr/bin/env python3
"""Turn Il2CppDumper's script.json into a build-frozen method name → RVA map.

Il2CppDumper (see tools/il2cppdump.sh) writes one record per managed method:

    {"Address": <VA>, "Name": "Namespace.Type$$Method", "Signature": "...",
     "TypeSignature": "..."}

`Address` is a virtual address in the dumped binary, so the RVA we can use
inside the game is `Address - ImageBase` where ImageBase comes from the PE
optional header of GameAssembly.dll. Nothing here calls into the game or
reinterprets IL2CPP internals: it is a pure file transform, which is exactly
what makes the "runtime dump → offline dumper → frozen table" pipeline safe.

    uv run --no-project python tools/il2cpp_methods.py script.json \
        --game-dir ~/.local/share/Steam/steamapps/common/VRChat \
        --out methods-<sha12>.json [--rust game_methods.rs] \
        [--filter UnityEngine] [--limit 20]

The JSON shape mirrors symbols-<sha12>.json (one file per GameAssembly hash):

    {"gameassembly_sha256": ..., "unity_version": ..., "image_base": ...,
     "count": N, "duplicates": M,
     "methods": [{"name", "type", "method", "signature", "rva", "va"}]}
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_GAME = Path.home() / ".local/share/Steam/steamapps/common/VRChat"


def pe_image_base(path: Path) -> int:
    """ImageBase of a PE32/PE32+ file; IL2CPP script addresses are VA-based."""
    with path.open("rb") as fh:
        data = fh.read(0x400)
    if data[:2] != b"MZ":
        raise SystemExit(f"{path}: not a PE file (no MZ signature)")
    pe_off = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe_off:pe_off + 4] != b"PE\0\0":
        raise SystemExit(f"{path}: missing PE signature at {pe_off:#x}")
    opt = pe_off + 24
    magic = struct.unpack_from("<H", data, opt)[0]
    if magic == 0x20B:      # PE32+
        return struct.unpack_from("<Q", data, opt + 24)[0]
    if magic == 0x10B:      # PE32
        return struct.unpack_from("<I", data, opt + 28)[0]
    raise SystemExit(f"{path}: unknown optional header magic {magic:#x}")


def unity_version(game_dir: Path | None) -> str | None:
    if not game_dir:
        return None
    matches = sorted(game_dir.glob("*_Data/globalgamemanagers"))
    if not matches:
        return None
    blob = matches[0].read_bytes()
    found = re.search(rb"(6000|20[0-9]{2})\.[0-9]+\.[0-9]+f[0-9]+", blob)
    return found.group(0).decode() if found else None


def split_name(name: str) -> tuple[str, str]:
    """'Namespace.Type$$Method' → ('Namespace.Type', 'Method')."""
    if "$$" in name:
        ty, method = name.split("$$", 1)
        return ty, method
    return "", name


def convert(script: dict, image_base: int) -> tuple[list[dict], int]:
    entries: list[dict] = []
    duplicates = 0
    seen: dict[tuple[str, str, str], int] = {}
    for item in script.get("ScriptMethod", []):
        address = item.get("Address")
        name = item.get("Name") or ""
        if address is None or not name or address < image_base:
            continue
        ty, method = split_name(name)
        key = (ty, method, item.get("Signature") or "")
        if key in seen:
            duplicates += 1
            continue
        seen[key] = 1
        entries.append({
            "name": name,
            "type": ty,
            "method": method,
            "signature": item.get("Signature") or "",
            "va": address,
            "rva": address - image_base,
        })
    entries.sort(key=lambda e: (e["rva"], e["name"]))
    return entries, duplicates


def rust_table(entries: list[dict], sha256: str, version: str | None) -> str:
    out = [
        "// @generated by tools/il2cpp_methods.py — do not edit by hand.",
        f"// GameAssembly sha256: {sha256}",
        f"// Unity: {version or 'unknown'}",
        "//! Managed method name → RVA inside GameAssembly.dll.",
        "//!",
        "//! Generated from Il2CppDumper's script.json (runtime metadata dump),",
        "//! so these RVAs are valid for exactly one GameAssembly hash.",
        "#[rustfmt::skip]",
        "pub static METHODS: &[(&str, u32)] = &[",
    ]
    for entry in entries:
        name = entry["name"].replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'    ("{name}", {entry["rva"]:#x}),')
    out.append("];")
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Convert Il2CppDumper script.json into a method name -> RVA map.")
    ap.add_argument("script_json", type=Path)
    ap.add_argument("--game-dir", type=Path, default=DEFAULT_GAME)
    ap.add_argument("--gameassembly", type=Path, default=None,
                    help="explicit GameAssembly.dll (default: <game-dir>/GameAssembly.dll)")
    ap.add_argument("--image-base", type=lambda v: int(v, 0), default=None,
                    help="override the PE ImageBase")
    ap.add_argument("--out", type=Path, default=None, help="write the JSON map here")
    ap.add_argument("--rust", type=Path, default=None, help="write a generated Rust table")
    ap.add_argument("--filter", default=None, help="keep only names containing this substring")
    ap.add_argument("--limit", type=int, default=20, help="how many entries to print (0 = none)")
    args = ap.parse_args(argv)

    if not args.script_json.is_file():
        print(f"no script.json at {args.script_json}", file=sys.stderr)
        return 2
    ga = args.gameassembly or (args.game_dir / "GameAssembly.dll")
    image_base = args.image_base if args.image_base is not None else pe_image_base(ga)
    sha = ""
    if ga.is_file():
        digest = hashlib.sha256()
        with ga.open("rb") as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b""):
                digest.update(chunk)
        sha = digest.hexdigest()
    version = unity_version(args.game_dir)

    script = json.loads(args.script_json.read_text())
    entries, duplicates = convert(script, image_base)
    if args.filter:
        needle = args.filter.lower()
        entries = [e for e in entries if needle in e["name"].lower()]

    print(f"image base {image_base:#x}, {len(entries)} method(s), {duplicates} duplicate name(s)")
    if entries:
        rvas = [e["rva"] for e in entries]
        print(f"rva range {min(rvas):#x}..{max(rvas):#x}")
    if args.limit:
        for entry in entries[:args.limit]:
            print(f"  {entry['rva']:#010x}  {entry['name']}")
    if args.limit and len(entries) > args.limit:
        print(f"  … {len(entries) - args.limit} more")

    if args.out:
        payload = {
            "gameassembly_sha256": sha,
            "unity_version": version,
            "image_base": image_base,
            "count": len(entries),
            "duplicates": duplicates,
            "methods": entries,
        }
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(payload, indent=1) + "\n")
        print(f"wrote {args.out}")
    if args.rust:
        args.rust.parent.mkdir(parents=True, exist_ok=True)
        args.rust.write_text(rust_table(entries, sha, version))
        print(f"wrote {args.rust}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
