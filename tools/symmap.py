#!/usr/bin/env python3
"""Generate the per-build symbol map for Hromatite.

Reads the installed game's GameAssembly.dll and UnityPlayer.dll and emits
`crates/hromatite-il2cpp/src/symbols.rs` (export name -> RVA) keyed by the
GameAssembly hash. Read-only with respect to the game.

Usage:
    uv run --no-project python tools/symmap.py [--game-dir DIR]

Why a generated file and not a runtime scan: Beebyte renames every export per
build, so the name list must be frozen together with the file hash. The DLL
then only needs the names, never the offsets.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import struct
import subprocess
import sys

OBJDUMP = "x86_64-w64-mingw32-objdump"
DEFAULT_GAME = os.path.expanduser(
    "~/.local/share/Steam/steamapps/common/VRChat"
)


def pe_headers(data: bytes):
    e_lfanew = struct.unpack_from("<I", data, 0x3C)[0]
    coff = e_lfanew + 4
    nsec = struct.unpack_from("<H", data, coff + 2)[0]
    opt_size = struct.unpack_from("<H", data, coff + 16)[0]
    opt = coff + 20
    magic = struct.unpack_from("<H", data, opt)[0]
    img_base = struct.unpack_from("<Q" if magic == 0x20B else "<I", data, opt + 24)[0]
    dd = opt + (112 if magic == 0x20B else 96)
    sections = []
    st = opt + opt_size
    for i in range(nsec):
        b = st + i * 40
        name = data[b:b + 8].rstrip(b"\0").decode(errors="replace")
        vsize, vaddr, rsize, raw = struct.unpack_from("<IIII", data, b + 8)
        sections.append((name, vaddr, max(vsize, rsize), raw, rsize))
    return img_base, dd, sections


def exports_with_rva(data: bytes):
    """name -> RVA via the export directory (authoritative, unlike objdump text)."""
    img_base, dd, sections = pe_headers(data)

    def rva2off(rva):
        for _, vaddr, size, raw, rsize in sections:
            if vaddr <= rva < vaddr + size:
                return raw + (rva - vaddr)
        return None

    exp_rva, exp_size = struct.unpack_from("<II", data, dd + 0)
    if not exp_rva:
        return {}
    d = rva2off(exp_rva)
    n_names = struct.unpack_from("<I", data, d + 24)[0]
    funcs = struct.unpack_from("<I", data, d + 28)[0]
    names = struct.unpack_from("<I", data, d + 32)[0]
    ords = struct.unpack_from("<I", data, d + 36)[0]
    out = {}
    for i in range(n_names):
        nrva = struct.unpack_from("<I", data, rva2off(names) + i * 4)[0]
        noff = rva2off(nrva)
        end = data.index(b"\0", noff)
        name = data[noff:end].decode(errors="replace")
        ordv = struct.unpack_from("<H", data, rva2off(ords) + i * 2)[0]
        frva = struct.unpack_from("<I", data, rva2off(funcs) + ordv * 4)[0]
        out[name] = frva
    return out


def unity_version(game: str) -> str:
    p = os.path.join(game, "VRChat_Data", "globalgamemanagers")
    if not os.path.exists(p):
        return "unknown"
    with open(p, "rb") as f:
        blob = f.read(4096)
    m = re.search(rb"(\d{4}\.\d+\.\d+[a-z]\d+)", blob)
    return m.group(1).decode() if m else "unknown"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--game-dir", default=DEFAULT_GAME)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..",
                                                  "crates/hromatite-il2cpp/src/symbols.rs"))
    args = ap.parse_args()
    game = args.game_dir.rstrip("/")

    ga_path = os.path.join(game, "GameAssembly.dll")
    up_path = os.path.join(game, "UnityPlayer.dll")
    ga = open(ga_path, "rb").read()
    up = open(up_path, "rb").read()

    sha = hashlib.sha256(ga).hexdigest()
    exports = exports_with_rva(ga)
    if not exports:
        print("no exports parsed", file=sys.stderr)
        return 1

    # Name pool inside UnityPlayer: the names Unity itself resolves at runtime.
    # Order is *not* assumed to match any published header, so we only record
    # presence and file order — the runtime resolves addresses empirically.
    pool = []
    for name in exports:
        i = up.find(name.encode() + b"\0")
        if i != -1:
            pool.append((i, name))
    pool.sort()

    lines = [
        "// @generated by tools/symmap.py - do not edit by hand.",
        f"pub const UNITY_VERSION: &str = \"{unity_version(game)}\";",
        f"pub const GAMEASSEMBLY_SHA256: &str = \"{sha}\";",
        f"pub const EXPORT_COUNT: usize = {len(exports)};",
        "",
        "/// (export name, RVA) for every export of GameAssembly.dll.",
        "pub const EXPORTS: &[(&str, u32)] = &[",
    ]
    for name, rva in sorted(exports.items(), key=lambda kv: kv[1]):
        lines.append(f"    ({name!r}, 0x{rva:08x}),".replace("'", '"'))
    lines.append("];")
    lines.append("")
    lines.append("/// UnityPlayer pool order (file offset, name) - diagnostics only.")
    lines.append("pub const POOL: &[(u32, &str)] = &[")
    for off, name in pool:
        lines.append(f"    (0x{off:08x}, \"{name}\"),")
    lines.append("];")
    lines.append("")

    with open(args.out, "w") as f:
        f.write("\n".join(lines))

    side = os.path.join(os.path.dirname(args.out), "..", "..", "..",
                        f"symbols-{sha[:12]}.json")
    with open(os.path.normpath(side), "w") as f:
        json.dump(
            {"sha256": sha, "unity": unity_version(game),
             "exports": exports, "pool": [{"off": o, "name": n} for o, n in pool]},
            f, indent=2, sort_keys=True,
        )

    print(f"unity {unity_version(game)}")
    print(f"sha256 {sha}")
    print(f"exports {len(exports)}, in unityplayer pool {len(pool)}")
    print(f"wrote {args.out}")
    print(f"wrote {os.path.normpath(side)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
